package android;
/** Platform resource id table; values live in framework-res and are resolved by name or inlined constants. */
public final class R {
 private R(){}
 public static final class attr { private attr(){} }
 public static final class bool { private bool(){} }
 public static final class color { private color(){} }
 public static final class dimen { private dimen(){} }
 public static final class drawable { private drawable(){} }
 public static final class id { private id(){} }
 public static final class integer { private integer(){} }
 public static final class layout { private layout(){} }
 public static final class string { private string(){} }
 public static final class style { private style(){} }
 public static final class styleable { private styleable(){} }
}
