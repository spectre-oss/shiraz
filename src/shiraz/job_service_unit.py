"""Render an opt-in Linux systemd user unit; never installs or enables it."""

from pathlib import PurePosixPath

from .apk import FormatError


def _path(value):
    value = str(value)
    if (
        not value.startswith('/')
        or '..' in PurePosixPath(value).parts
        or any(ord(c) < 32 or ord(c) == 127 for c in value)
    ):
        raise FormatError(
            'Service paths must be absolute without control characters or parent traversal'
        )
    return value


def _quote(value):
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"').replace('%', '%%') + '"'


def render(checkout, interpreter, registry):
    checkout, interpreter, registry = map(_path, (checkout, interpreter, registry))
    if ':' in checkout:
        raise FormatError('Checkout path cannot contain the PYTHONPATH separator')
    source = str(PurePosixPath(checkout) / 'src')
    # ':' disables command environment expansion; '%' still requires doubling.
    # systemd owns restarts directly, so no nested supervise-jobs process is used.
    return '\n'.join(
        [
            '# Generated by Shiraz; review paths on the target Linux host before installation.',
            '[Unit]',
            'Description=Shiraz background job host',
            'StartLimitIntervalSec=60',
            'StartLimitBurst=10',
            '',
            '[Service]',
            'Type=exec',
            'Environment=' + _quote('PYTHONPATH=' + source),
            'ExecStart=:'
            + _quote(interpreter)
            + ' -m shiraz serve-jobs --registry '
            + _quote(registry),
            'Restart=on-failure',
            'RestartSec=2',
            'TimeoutStopSec=30',
            'KillMode=mixed',
            'UMask=0077',
            'StandardInput=null',
            'StandardOutput=journal',
            'StandardError=journal',
            '',
            '[Install]',
            'WantedBy=default.target',
            '',
        ]
    )
