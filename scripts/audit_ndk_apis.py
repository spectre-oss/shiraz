def exported_symbols(lib_path: Path) -> set[str]:
    if not lib_path.exists():
        return set()
    is_darwin = platform.system() == "Darwin"
    cmd = (
        ["nm", "-gU", str(lib_path)] if is_darwin else ["nm", "-D", "--defined-only", str(lib_path)]
    )
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        return set()
    symbols = set()
    for line in proc.stdout.splitlines():
        parts = line.split()
        if not parts:
            continue
        name = parts[-1]
        if is_darwin and name.startswith("_"):
            name = name[1:]
        symbols.add(name)
    return symbols


def audit_directory(lib_dir: Path) -> dict:
    libraries = []
    total_ref = 0
    total_present = 0
    libs_present = 0

    for lib_name, families in NDK_CATALOG.items():
        path = lib_dir / lib_name
        exists = path.exists()
        if exists:
            libs_present += 1
        syms = exported_symbols(path)
        lib_ref = 0
        lib_present = 0
        family_rows = []
        for fam_name, expected in families.items():
            present = [s for s in expected if s in syms]
            missing = [s for s in expected if s not in syms]
            lib_ref += len(expected)
            lib_present += len(present)
            family_rows.append(
                {
                    "family": fam_name,
                    "present": len(present),
                    "reference": len(expected),
                    "missing": len(missing),
                    "missing_symbols": missing,
                }
            )
        total_ref += lib_ref
        total_present += lib_present
        libraries.append(
            {
                "library": lib_name,
                "exists": exists,
                "present": lib_present,
                "reference": lib_ref,
                "missing": lib_ref - lib_present,
                "families": family_rows,
            }
        )

    try:
        display_dir = str(lib_dir.resolve().relative_to(ROOT))
    except ValueError:
        display_dir = str(lib_dir)

    return {
        "lib_dir": display_dir,
        "libraries_present": libs_present,
        "libraries_total": len(NDK_CATALOG),
        "symbols_present": total_present,
        "symbols_reference": total_ref,
        "symbols_missing": total_ref - total_present,
        "percent": round(100.0 * total_present / total_ref, 2) if total_ref else 0.0,
        "libraries": libraries,
    }


def render_ndk_markdown(report: dict) -> str:
    lines = [
        "## 5. NDK native libraries",
        "",
        f"Audited directly from compiled shared libraries in `{report['lib_dir']}` using `nm` "
        f"against the Shiraz Android API 35 NDK catalog (`scripts/audit_ndk_apis.py`).",
        "",
        f"**{report['libraries_present']} of {report['libraries_total']} NDK libraries built; "
        f"{report['symbols_present']} of {report['symbols_reference']} tracked NDK symbols exported "
        f"({report['percent']:.1f}%); {report['symbols_missing']} missing.**",
        "",
        "| Library | File | Present | Reference | Missing | Coverage |",
        "|---|---|--:|--:|--:|--:|",
    ]
    for lib in report["libraries"]:
        status = "built" if lib["exists"] else "missing"
        pct = 100.0 * lib["present"] / lib["reference"] if lib["reference"] else 0.0
        lines.append(
            f"| `{lib['library']}` | {status} | {lib['present']} | {lib['reference']} | "
            f"{lib['missing']} | {pct:.1f}% |"
        )
    missing_fams = []
    for lib in report["libraries"]:
        for fam in lib["families"]:
            if fam["missing"] > 0:
                missing_fams.append((lib["library"], fam))
    if missing_fams:
        lines.extend(
            [
                "",
                "### Remaining missing NDK API families",
                "",
                "| Library | Family | Present | Reference | Missing |",
                "|---|---|--:|--:|--:|",
            ]
        )
        for lib_name, fam in missing_fams:
            lines.append(
                f"| `{lib_name}` | `{fam['family']}` | {fam['present']} | "
                f"{fam['reference']} | {fam['missing']} |"
            )
    else:
        lines.extend(
            [
                "",
                "All 15 tracked NDK native libraries and all tracked API families are built and "
                "export 100% of cataloged C entry points.",
            ]
        )
    return "\n".join(lines) + "\n"


def update_missing_doc(report: dict, doc_path: Path) -> None:
    text = doc_path.read_text()
    start_marker = "## 5. NDK native libraries\n"
    end_marker = "\n## 6. Every missing class\n"
    start = text.index(start_marker)
    end = text.index(end_marker)
    new_section = render_ndk_markdown(report)
    doc_path.write_text(text[:start] + new_section + text[end:])


def main() -> int:
    default_dir = ROOT / ("build/macos" if platform.system() == "Darwin" else "build")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", type=Path, default=default_dir, help="Built libraries directory")
    parser.add_argument("--json", action="store_true", help="Emit JSON report")
    parser.add_argument(
        "--write-missing-doc",
        action="store_true",
        help="Update section 5 of docs/MISSING_ANDROID_LIBRARIES.md",
    )
    parser.add_argument(
        "--require-complete",
        action="store_true",
        help="Exit non-zero if any cataloged NDK symbol is missing",
    )
    args = parser.parse_args()

    report = audit_directory(args.dir)
    if args.write_missing_doc:
        update_missing_doc(report, ROOT / "docs/MISSING_ANDROID_LIBRARIES.md")

    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(
            f"NDK libraries: {report['libraries_present']}/{report['libraries_total']} built | "
            f"symbols: {report['symbols_present']}/{report['symbols_reference']} "
            f"({report['percent']:.2f}%)"
        )
        for lib in report["libraries"]:
            mark = "OK" if lib["missing"] == 0 else "GAP"
            print(
                f"  [{mark}] {lib['library']:22s} {lib['present']:3d}/{lib['reference']:3d}"
                + ("" if lib["exists"] else " (file missing)")
            )
    if args.require_complete and report["symbols_missing"] > 0:
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
